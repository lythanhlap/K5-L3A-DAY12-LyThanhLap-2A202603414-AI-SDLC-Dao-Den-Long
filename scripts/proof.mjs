// Runs every scenario through the real headless CLI, checks expectations, verifies determinism
// (two runs, sha256 compare) and writes docs/proof/<phase>/RESULTS.md + raw .jsonl outputs.
// Usage: npm run proof [-- phase-1]
import { createHash } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join } from 'node:path';
import os from 'node:os';
import { scenarios, runScenario, checkExpectations, argsFor, ROOT } from './scenarios.mjs';

const phase = process.argv[2] || 'phase-1';
const outDir = join(ROOT, 'docs/proof', phase);
const runs = join(outDir, 'runs');
const sha = (t) => createHash('sha256').update(t).digest('hex').slice(0, 16);
const rel = (p) => p.replace(ROOT, '.').replace(/\\/g, '/');

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: ROOT, encoding: 'utf8' }).trim();
  if (execSync('git status --porcelain -- src scenarios', { cwd: ROOT, encoding: 'utf8' }).trim()) commit += ' (+uncommitted changes)';
} catch {}

const rows = [];
let allOk = true;
for (const s of scenarios) {
  const a = runScenario(s, runs);
  const b = runScenario(s, join(runs, '.rerun'));
  const det = a.text === b.text;
  const checks = checkExpectations(s, a.lines);
  const ok = det && checks.every((c) => c.ok);
  allOk &&= ok;
  rows.push({ s, a, det, checks, ok });
  console.log(`${ok ? 'PASS' : 'FAIL'} ${s.name}${det ? '' : ' (non-deterministic!)'}`);
  for (const c of checks.filter((c) => !c.ok)) console.log(`   ${c.check} -> ${c.detail}`);
}

const md = [
  `# Proof ${phase}: headless scenarios`,
  '',
  `Generated by \`npm run proof -- ${phase}\` (do not edit by hand). Commit: \`${commit}\`.`,
  `Machine: ${os.type()} ${os.release()} ${os.arch()}, ${os.cpus()[0]?.model ?? ''}, Node ${process.version}.`,
  '',
  '| Scenario | AC | What it shows | Determinism (sha256 x2) | Checks | Result |',
  '|---|---|---|---|---|---|',
  ...rows.map(({ s, a, det, checks, ok }) =>
    `| [${s.name}](runs/${s.name}.jsonl) | ${s.ac} | ${s.why} | ${det ? `same \`${sha(a.text)}\`` : '**DIFFERENT**'} | ${checks.filter((c) => c.ok).length}/${checks.length} | ${ok ? 'PASS' : '**FAIL**'} |`),
  '',
  '## Commands',
  '',
  ...rows.map(({ s }) => `- \`node src/headless.js ${argsFor(s, `runs/${s.name}.jsonl`).map(rel).join(' ')}\``),
  '',
  '## Check details',
  '',
  ...rows.flatMap(({ s, checks }) => [`### ${s.name}`, ...checks.map((c) => `- ${c.ok ? '✅' : '❌'} \`${c.check}\` → ${c.detail}`), '']),
];
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'RESULTS.md'), md.join('\n') + '\n');
console.log(`\nwrote ${rel(join(outDir, 'RESULTS.md'))}`);
process.exit(allOk ? 0 : 1);
